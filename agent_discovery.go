package sdk

import (
	"context"
	"net/http"

	product "github.com/matrixorigin/moi-go-sdk/v5/product"
)

type ExecutorHealth = product.ExecutorHealth
type ExecutorHealthResponse = product.ExecutorHealthResponse

// List uses the root agent catalog route used by the agent picker.
func (s *AgentService) List(ctx context.Context, opts ...QueryOption) (*ProductData, error) {
	var out ProductData
	err := s.do(ctx, http.MethodGet, withQuery("/agents", opts), nil, &out)
	return &out, err
}

func (s *AgentService) ExecutorHealth(ctx context.Context) (*ExecutorHealthResponse, error) {
	var out ExecutorHealthResponse
	err := s.do(ctx, http.MethodGet, "/agent-executors/health", nil, &out)
	return &out, err
}

// PreviewQueryVisual streams the image generated by an agent query.
func (s *AgentService) PreviewQueryVisual(ctx context.Context, agentID, fileID string) (*StreamResponse, error) {
	agent, err := pathID(agentID)
	if err != nil {
		return nil, err
	}
	file, err := pathID(fileID)
	if err != nil {
		return nil, err
	}
	workspace, err := pathID(s.workspaceID)
	if err != nil {
		return nil, err
	}
	return s.doDownload(ctx, http.MethodGet, "/workspaces/"+workspace+"/agents/"+agent+"/query-visuals/"+file+"/preview", nil)
}
